#!/usr/bin/env python3
"""mkotnames.py OUT.h HEADER... - OTNames.h: maps every `pascal` function of Open Transport's headers to the
upper-case name MPW's object files carry (`#define OTCreateConfiguration OTCREATECONFIGURATION`). MPW stores Pascal
symbols in capitals; Symantec C++ 7 looks them up as written, so without this map every OT call is "undefined" at
link time. Include OTNames.h before the OT headers (OTCompat.h does), so the declarations are renamed as well."""
import re, sys

out, headers = sys.argv[1], sys.argv[2:]
names = set()
for h in headers:
    text = open(h, encoding="mac_roman", errors="replace").read().replace("\r", "\n")
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    for m in re.finditer(r"\bpascal\b[^;{()]*?\b([A-Za-z_][A-Za-z0-9_]*)\s*\(", text):
        n = m.group(1)
        if n != n.upper() and n != n.lower():   # skips keywords such as `void` in "pascal void (*ProcPtr)(...)"
            names.add(n)
lines = ["/* OTNames.h - generated by tools/mkotnames.py from " + ", ".join(h.rsplit("/", 1)[-1] for h in headers) + ".",
         "   Open Transport's pascal functions under the upper-case names of MPW's 68K object files. */", "",
         "#ifndef __OTNAMES__", "#define __OTNAMES__", ""]
lines += ["#define %-40s %s" % (n, n.upper()) for n in sorted(names)]
lines += ["", "#endif", ""]
open(out, "w", encoding="mac_roman").write("\n".join(lines))
print(out, len(names), "names")
